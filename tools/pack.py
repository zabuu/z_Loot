# Packs Data.lua and Collections.lua into Packed.lua as quoted strings (Lua 5.0 safe).
# At login the game keeps only two strings; Init.lua unpacks them with loadstring on first open.
import sys, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def q(s):
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == '\\': out.append('\\\\')
        elif ch == '"': out.append('\\"')
        elif ch == '\n': out.append('\\n')
        elif o < 32 or o == 127: out.append('\\%03d' % o)
        else: out.append(ch)
    out.append('"')
    return ''.join(out)
parts = []
for name in ('Data.lua', 'Collections.lua'):
    src = open(os.path.join(root, 'src', name), encoding='latin-1').read()
    parts.append(q(src))
with open(os.path.join(root, 'Packed.lua'), 'w', encoding='latin-1', newline='\n') as f:
    f.write('-- Generated by tools/pack.py from src/Data.lua and src/Collections.lua. Do not edit.\n')
    f.write('ZL_PackedData = {\n' + ',\n'.join(parts) + '\n}\n')
